def svg(name, color=theme.FOREGROUND, stroke=1.8):
    body = PATHS[name].replace("CURRENT", color)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')


def pixmap(name, size=20, color=theme.FOREGROUND, stroke=1.8, dpr=2.0):
    renderer = QSvgRenderer(QByteArray(svg(name, color, stroke).encode()))
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(p, QRectF(0, 0, size * dpr, size * dpr))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name, size=20, color=theme.FOREGROUND, stroke=1.8):
    return QIcon(pixmap(name, size, color, stroke))


def qsize(n):
    return QSize(n, n)
